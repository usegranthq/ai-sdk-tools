// Generates src/generated/tools.gen.ts with an AI SDK tool for every operation of the UseGrant OpenAPI spec.
// The tools call the methods of the generated @usegrant/sdk client and use its zod schemas as the input schema.
//
// Usage: node scripts/generate-tools.mjs [spec url or path]

import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

import * as schemas from '@usegrant/sdk/schema';

const SPEC_URL = 'https://sdk.usegrant.dev/open-api.json';
const OUTPUT = 'src/generated/tools.gen.ts';
const METHODS = ['get', 'put', 'post', 'delete', 'patch'];

const loadSpec = async (source) => {
  if (/^https?:\/\//.test(source)) {
    const response = await fetch(source);
    if (!response.ok) {
      throw new Error(`Failed to fetch ${source}: ${response.status}`);
    }
    return response.json();
  }
  return JSON.parse(await readFile(source, 'utf8'));
};

// same naming as hey-api, `providers.clients.create` -> `ProvidersClientsCreate`
const pascalCase = (operationId) =>
  operationId
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');

const toolName = (operationId) => operationId.replace(/[^A-Za-z0-9_-]+/g, '_');

const operations = (spec) =>
  Object.values(spec.paths ?? {}).flatMap((pathItem) =>
    METHODS.flatMap((method) => (pathItem[method] ? [pathItem[method]] : [])),
  );

const generateTool = (operation) => {
  const { operationId } = operation;
  if (!operationId) {
    throw new Error(`Missing operationId for "${operation.summary}"`);
  }

  const name = pascalCase(operationId);
  // the sdk only exports the schemas an operation has
  const inputs = ['Path', 'Query', 'Body']
    .map((part) => `z${name}${part}`)
    .filter((schema) => schema in schemas);
  const hasResponse = `z${name}Response` in schemas;

  const description = JSON.stringify(operation.summary ?? operation.description ?? operationId);
  const inputSchema =
    inputs.length === 0
      ? 'z.object({})'
      : inputs.slice(1).reduce((schema, next) => `${schema}.extend(${next}.shape)`, inputs[0]);
  const call =
    inputs.length === 0
      ? `usegrant.${operationId}({ signal: abortSignal })`
      : `usegrant.${operationId}(input, { signal: abortSignal })`;
  const execute = hasResponse
    ? `(await ${call}).data`
    : `{ await ${call}; return ${JSON.stringify(`${operation.summary ?? operationId} succeeded`)}; }`;

  return {
    inputs,
    code: `  ${toolName(operationId)}: tool({
    description: ${description},
    inputSchema: ${inputSchema},
    execute: async (${inputs.length === 0 ? '_input' : 'input'}, { abortSignal }) => ${execute},
  }),`,
  };
};

const spec = await loadSpec(process.argv[2] ?? SPEC_URL);
const tools = operations(spec).map(generateTool);
const imports = tools.flatMap((tool) => tool.inputs).sort();

const source = `// This file is auto-generated by scripts/generate-tools.mjs, do not edit it by hand

import type { UseGrant } from '@usegrant/sdk';
import { ${imports.join(', ')} } from '@usegrant/sdk/schema';
import { tool } from 'ai';
import { z } from 'zod';

export const createUseGrantTools = (usegrant: UseGrant) => ({
${tools.map((tool) => tool.code).join('\n')}
});
`;

await mkdir('src/generated', { recursive: true });
await writeFile(OUTPUT, source);
execFileSync('npx', ['oxfmt', OUTPUT], { stdio: 'inherit' });

console.log(`Generated ${tools.length} tools in ${OUTPUT}`);
